"""
=========================================================================
 bot.py — Telegram-бот для портфолио "Tim Taler — No-Code архитектор"
=========================================================================
Библиотека: aiogram 3.x (актуальный стабильный релиз на середину 2026 —
ветка 3.x, самая свежая на момент написания — 3.30.x, но код ниже
совместим с любой версией 3.x).

Что делает этот бот, по шагам:
  1. Пользователь пишет боту /start.
  2. Бот отвечает приветствием и показывает inline-кнопку с типом
     web_app — при нажатии Telegram откроет наш index.html прямо
     внутри мессенджера (это и есть Mini App).
  3. Когда пользователь заполняет форму в Mini App и жмёт "Отправить",
     наш index.html вызывает Telegram.WebApp.sendData(...).
     Telegram доставляет эти данные боту как обычное сообщение,
     у которого заполнено специальное поле web_app_data.
     Мы ловим такие сообщения отдельным хэндлером, разбираем JSON
     и присылаем пользователю (владельцу бота) красивое сообщение
     с деталями заявки.

Установка зависимостей (один раз, в терминале):
    pip install aiogram

Запуск бота:
    python bot.py
=========================================================================
"""

import asyncio
import json
import logging

from aiogram import Bot, Dispatcher, F
from aiogram.client.default import DefaultBotProperties
from aiogram.enums import ContentType, ParseMode
from aiogram.filters import CommandStart
from aiogram.types import (
    KeyboardButton,
    Message,
    ReplyKeyboardMarkup,
    WebAppInfo,
)

# =========================================================================
# 1. НАСТРОЙКИ — впиши сюда свои значения перед первым запуском
# =========================================================================

# Токен бота, который тебе выдал @BotFather после команды /newbot.
# Выглядит примерно так: "123456789:AAExampleTokenDoNotUseThisOne"
#
# ВАЖНО про безопасность: токен — это как пароль от бота. Если будешь
# выкладывать этот код на GitHub — не забудь удалить токен из файла
# (или вынести его в переменную окружения через os.getenv("BOT_TOKEN")).
BOT_TOKEN = "8844337587:AAG7xs5avqRDwoUahIZoXDsoTaPJwc7m0JI"

# HTTPS-ссылка на index.html. Во время локального теста сюда нужно
# вставить адрес, который выдаст ngrok (см. пошаговую инструкцию в чате).
# Telegram категорически не откроет Mini App по адресу вида
# http://localhost:8000 — обязательно нужен именно https.
WEB_APP_URL = "https://talerkrone-hash.github.io/tg-miniapp/"

# Включаем логирование, чтобы в консоли было видно, что бот делает
# и на каком шаге, если вдруг что-то пойдёт не так.
logging.basicConfig(level=logging.INFO)


# =========================================================================
# 2. Создаём объекты бота и диспетчера
# =========================================================================

# DefaultBotProperties(parse_mode=ParseMode.HTML) — говорит боту, что
# по умолчанию во всех сообщениях можно использовать простую HTML-разметку
# (например, <b>жирный текст</b>), без необходимости указывать это
# в каждом вызове message.answer() отдельно.
bot = Bot(token=BOT_TOKEN, default=DefaultBotProperties(parse_mode=ParseMode.HTML))

# Dispatcher — это "диспетчер", который получает все входящие сообщения
# от Telegram и раздаёт их нужным функциям-обработчикам (хэндлерам) ниже.
dp = Dispatcher()


# =========================================================================
# 3. Хэндлер команды /start
# =========================================================================

@dp.message(CommandStart())
async def cmd_start(message: Message) -> None:
    """
    Срабатывает, когда пользователь отправляет боту команду /start
    (это происходит автоматически при первом открытии чата с ботом,
    либо если ввести /start вручную).
    """

    # Формируем inline-клавиатуру с одной кнопкой особого типа — web_app.
    # Именно такая кнопка (а не обычная URL-кнопка) открывает ссылку
    # ВНУТРИ Telegram, как полноценное мини-приложение, а не в браузере.
    keyboard = ReplyKeyboardMarkup(
        keyboard=[
            [
                KeyboardButton(
                    text="🚀 Открыть портфолио",
                    web_app=WebAppInfo(url=WEB_APP_URL),
                )
            ]
        ],
        resize_keyboard=True,
    )

    await message.answer(
        "Привет! 👋\n\n"
        "Я <b>Tim Taler</b> — No-Code архитектор мобильных приложений "
        "и экосистем Telegram &amp; .gram.\n\n"
        "Нажми на кнопку ниже, чтобы открыть моё портфолио "
        "и оставить заявку 👇",
        reply_markup=keyboard,
    )


# =========================================================================
# 4. Хэндлер данных, присланных из Mini App (Telegram.WebApp.sendData)
# =========================================================================

# Фильтр F.content_type == ContentType.WEB_APP_DATA означает:
# "сработай только на сообщения, у которых тип контента — web_app_data".
# Именно такое служебное сообщение Telegram создаёт автоматически, когда
# наш index.html вызывает Telegram.WebApp.sendData(...).
@dp.message(F.content_type == ContentType.WEB_APP_DATA)
async def handle_web_app_data(message: Message) -> None:
    """
    Ловит данные формы из Mini App, разбирает их как JSON
    и присылает пользователю сообщение с деталями заявки.
    """

    # message.web_app_data.data — это ровно та строка, которую мы
    # передали в JS через JSON.stringify(data) внутри sendData(...).
    raw_data = message.web_app_data.data

    try:
        data = json.loads(raw_data)
    except json.JSONDecodeError:
        # На случай, если пришли "битые" данные (не valid JSON) —
        # не роняем бота, а вежливо сообщаем об ошибке.
        await message.answer("Не удалось разобрать данные из формы 😕")
        return

    # .get(..., "не указано") — безопасное чтение поля: если вдруг
    # какого-то ключа не окажется в JSON, бот не упадёт с ошибкой,
    # а подставит запасной текст.
    name = data.get("name", "не указано")
    phone = data.get("phone", "не указано")
    task = data.get("task", "не указано")

    await message.answer(
        "📩 <b>Новая заявка!</b>\n\n"
        f"👤 Имя: {name}\n"
        f"📱 Телефон: {phone}\n"
        f"📝 Задача: {task}"
    )


# =========================================================================
# 5. Точка входа — запуск бота
# =========================================================================

async def main() -> None:
    # drop_pending_updates=True — на всякий случай "сбрасываем" старые
    # сообщения, которые могли накопиться, пока бот был выключен,
    # чтобы при запуске не было наплыва неактуальных обновлений.
    await bot.delete_webhook(drop_pending_updates=True)

    # start_polling — бот начинает постоянно спрашивать у серверов
    # Telegram: "есть новые сообщения для меня?". Это самый простой
    # способ запуска бота для локальной разработки (без своего сервера).
    await dp.start_polling(bot)


if __name__ == "__main__":
    asyncio.run(main())
